"""Regenerate dashboard/src/lib/swarm-key-vectors.json (issue #122).

The dashboard creates swarm root keys and signs hub appointments in the
browser. These vectors pin the bytes it must produce: the key string format,
the public key and swarm ID for a seed, the canonical appointment bytes and
the Ed25519 signature. ``server/tests/test_swarm_key_vectors.py`` checks this
file against Python and the dashboard's ``swarmKey.test.js`` checks it against
JavaScript, so either side drifting fails CI.

Deterministic: fixed seeds, fixed timestamps. TEST KEYS ONLY; never register them.

    python -m scripts.make_swarm_key_vectors
"""
from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path

from nacl.signing import SigningKey

from ltms_contract import canonicalize

OUT = Path(__file__).resolve().parents[1] / "dashboard" / "src" / "lib" / "swarm-key-vectors.json"

KEY_PREFIX = "ltms-swarm-key-v1"
SWARM_PREFIX = b"ltms-swarm-v1\n"  # must match server/services/swarms.py


def encode_key(seed: bytes) -> str:
    """``ltms-swarm-key-v1:<base64url seed, no padding>:<first 8 hex of sha256(seed)>``."""
    b64 = base64.urlsafe_b64encode(seed).rstrip(b"=").decode("ascii")
    return f"{KEY_PREFIX}:{b64}:{hashlib.sha256(seed).hexdigest()[:8]}"


def build() -> dict:
    keys = []
    for i in (1, 2, 3):
        seed = bytes([i]) * 32
        pub = bytes(SigningKey(seed).verify_key)
        keys.append({
            "seed_hex": seed.hex(),
            "key_string": encode_key(seed),
            "public_key": pub.hex(),
            "swarm_id": hashlib.sha256(pub).hexdigest(),
        })

    root = SigningKey(bytes([1]) * 32)
    swarm_id = keys[0]["swarm_id"]
    appointments = []
    for hub, hub_seed, ts in (("jetson-hub", 4, "2026-11-08T12:00:00.000Z"),
                              ("hub.backup_2", 5, "2026-11-09T23:59:59.999Z")):
        hub_key = bytes(SigningKey(bytes([hub_seed]) * 32).verify_key).hex()
        statement = {"v": 1, "action": "appoint_hub", "swarm": swarm_id, "hub": hub,
                     "hub_key": hub_key, "ts": ts}
        message = SWARM_PREFIX + canonicalize(statement)
        appointments.append({
            "root_seed_hex": root.encode().hex(),
            "hub_seed_hex": (bytes([hub_seed]) * 32).hex(),
            "statement": statement,
            "canonical": canonicalize(statement).decode("utf-8"),
            "message_hex": message.hex(),
            "sig": root.sign(message).signature.hex(),
        })

    return {
        "note": "Generated by scripts/make_swarm_key_vectors.py. TEST KEYS ONLY; never register them.",
        "key_prefix": KEY_PREFIX,
        "swarm_prefix": SWARM_PREFIX.decode("ascii"),
        "keys": keys,
        "appointments": appointments,
    }


def render() -> str:
    return json.dumps(build(), indent=2) + "\n"


def main() -> None:
    OUT.write_text(render())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
