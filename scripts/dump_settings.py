def _clean(text: str) -> str:
    text = _ENV_SENTENCE.sub("", text)
    text = re.sub(r"\s+", " ", text).strip()
    return text.replace("|", "\\|")


def _yaml_defaults() -> dict:
    return (yaml.safe_load(DEFAULT_YAML.read_text()) or {}) if DEFAULT_YAML.exists() else {}


def default_value(name: str):
    """The default LTMS uses when the variable is unset: config/default.yaml, else the field."""
    yml = _yaml_defaults()
    if name in yml:
        return yml[name]
    field = ServerConfig.model_fields[name]
    if field.default_factory is not None:
        value = field.default_factory()
    else:
        value = None if field.default is PydanticUndefined else field.default
    if isinstance(value, list):
        value = [v.model_dump(exclude_none=True) if hasattr(v, "model_dump") else v for v in value]
    return value


def env_text(value) -> str:
    """How a default is written in an env file."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (dict, list)):
        return json.dumps(value, separators=(",", ":"))
    return str(value)


def about(name: str, code: dict[str, str], yml: dict[str, str]) -> str:
    for text in (ABOUT.get(name), code.get(name), yml.get(name)):
        if text and _clean(text):
            text = _clean(text)
            return text[0].upper() + text[1:]
    return ""


def settings() -> list[dict]:
    code, yml = _comments(), _yaml_comments()
    return [{"name": n, "env": env_name(n), "default": env_text(default_value(n)),
             "about": about(n, code, yml), "dashboard": DASHBOARD.get(n, "")}
            for n in ServerConfig.model_fields]


