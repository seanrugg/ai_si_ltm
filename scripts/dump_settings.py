DOCS_HEADER = """# Configuration

<!-- GENERATED by `python -m scripts.dump_settings` from server/config.py. Do not edit by hand. -->

Where LTMS reads its settings depends on how it is deployed. Settings →
System status shows which one this server is.

| Deployment | Settings file | After editing |
|---|---|---|
| Docker Compose | `.env` next to `compose.yaml` | `docker compose up -d` (recreates the `ltms` container) |
| systemd service | `/etc/ltms/ltms.env` | restart the service (`systemctl restart ltms`) |

Every setting below is read when LTMS starts, so a change needs the restart
above. With Compose, every setting in this list is passed from `.env` to the
`ltms` container (`compose.yaml` lists them all; a test keeps that list
complete). Other services' values in `.env`, such as the LRS admin password,
are not passed to `ltms`.

Defaults come from `config/default.yaml`, then the code. A variable that is
unset or empty uses the default. Some settings can also be changed on the
dashboard: there, the dashboard's value wins unless the matching `*_LOCKED`
setting is true.

| Setting | Default | Also on the dashboard | What it does |
|---|---|---|---|
"""


def render_docs() -> str:
    rows = []
    for s in settings():
        default = f"`{s['default']}`" if s["default"] != "" else "(empty)"
        rows.append(f"| `{s['env']}` | {default} | {s['dashboard']} | {s['about']} |")
    return DOCS_HEADER + "\n".join(rows) + "\n"


# --- compose.yaml ----------------------------------------------------------------

def _ltms_environment_lines(text: str) -> tuple[int, int]:
    """(start, end) line indexes of the ltms service's environment mapping body."""
    lines = text.splitlines()
    svc = next(i for i, line in enumerate(lines) if line == "  ltms:")
    env = next(i for i in range(svc + 1, len(lines)) if lines[i] == "    environment:")
    end = env + 1
    while end < len(lines) and (lines[end].startswith("      ") or not lines[end].strip()):
        end += 1
    return env + 1, end


def render_compose(text: str) -> str:
    lines = text.splitlines()
    start, end = _ltms_environment_lines(text)
    body = lines[start:end]
    if BEGIN.strip() in [b.strip() for b in body]:
        b = next(i for i, line in enumerate(body) if line.strip() == BEGIN)
        e = next(i for i, line in enumerate(body) if line.strip() == END)
        hand, tail = body[:b], body[e + 1:]
    else:
        hand, tail = body, []
    named = {m.group(1) for line in hand if (m := re.match(r"\s+(LTMS_[A-Z0-9_]+):", line))}
    gen = ["      " + BEGIN,
           "      # Every other LTMS setting, passed from .env when set there (docs/configuration.md).",
           "      # Empty values are ignored, so the defaults apply."]
    for s in settings():
        if s["name"] in COMPOSE_SKIP or s["env"] in named:
            continue
        gen.append(f"      {s['env']}: ${{{s['env']}:-}}")
    gen.append("      " + END)
    new = lines[:start] + hand + gen + tail + lines[end:]
    return "\n".join(new) + "\n"


# --- example env files -------------------------------------------------------------

def render_env_example(text: str, intro: str, skip: set[str] = frozenset()) -> str:
    """Replace (or append) the generated block of commented settings."""
    lines = text.rstrip("\n").splitlines()
    if BEGIN in lines:
        b, e = lines.index(BEGIN), lines.index(END)
        before, after = lines[:b], lines[e + 1:]
    else:
        before, after = lines + [""], []
    mentioned = set(re.findall(r"\b(LTMS_[A-Z0-9_]+)", "\n".join(before + after)))
    block = [BEGIN, *intro.splitlines()]
    for s in settings():
        if s["env"] in mentioned or s["name"] in skip:
            continue
        block.append(f"# {s['env']}={s['default']}")
    block.append(END)
    return "\n".join(before + block + after) + "\n"


COMPOSE_ENV_INTRO = """# All other LTMS settings, with their defaults. Uncomment and edit a line to
# change one, then run `docker compose up -d`. What each one does:
# docs/configuration.md."""
SERVICE_ENV_INTRO = """# All other LTMS settings, with their defaults. Uncomment and edit a line to
# change one, then restart the service. What each one does: docs/configuration.md."""


def render_setup_env(text: str, template: str) -> str:
    """scripts/setup_env.py with its embedded template replaced by ``template``."""
    if '"""' in template or "\\" in template:
        raise ValueError("the Compose example can't contain triple quotes or backslashes")
    head = '_EMBEDDED_TEMPLATE = """'
    start = text.index(head) + len(head)
    end = text.index('"""', start)
    return text[:start] + template + text[end:]


def outputs() -> dict[Path, str]:
    compose_env = render_env_example(COMPOSE_ENV.read_text(), COMPOSE_ENV_INTRO, COMPOSE_SKIP | COMPOSE_FIXED)
    return {
        DOCS: render_docs(),
        COMPOSE: render_compose(COMPOSE.read_text()),
        COMPOSE_ENV: compose_env,
        SERVICE_ENV: render_env_example(SERVICE_ENV.read_text(), SERVICE_ENV_INTRO),
        SETUP_ENV: render_setup_env(SETUP_ENV.read_text(), compose_env),
    }


def main(argv: list[str] | None = None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = []
    for path, text in outputs().items():
        if not path.exists() or path.read_text() != text:
            stale.append(path)
            if not check:
                path.write_text(text)
                print(f"wrote {path.relative_to(ROOT)}")
    if check and stale:
        print("out of date (run: python -m scripts.dump_settings): "
              + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
