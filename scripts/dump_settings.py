"""Regenerate the settings list from ``server/config.py`` (issue #390).

``server.config.ServerConfig`` is the single source of truth for LTMS settings.
This script writes, from it:

* ``docs/configuration.md``: every setting, its env var, default and meaning;
* the generated part of the ``ltms`` service's ``environment:`` in
  ``compose.yaml``, so every setting in ``.env`` reaches the container;
* the commented "all other settings" block of ``deploy/compose/.env.example``
  and ``deploy/ltms.env.example``, and the copy of the former embedded in
  ``scripts/setup_env.py``.

A test fails when any of them drifts:  python -m scripts.dump_settings
(``--check`` only reports, exit 1 when something is out of date).
"""
from __future__ import annotations

