_ENV_SENTENCE = re.compile(r"\s*Env(?: override)?:\s*(?:LTMS_[A-Z0-9_]+(?:,\s*)?)+\.?", re.IGNORECASE)


def env_name(name: str) -> str:
    alias = ServerConfig.model_fields[name].validation_alias
    if isinstance(alias, AliasChoices):
        for choice in alias.choices:
            if isinstance(choice, str) and choice.startswith("LTMS_"):
                return choice
    return f"LTMS_{name.upper()}"


def _comments() -> dict[str, str]:
    """Each ServerConfig field's comment: the comment lines just above it, plus any inline one."""
    src = CONFIG_PY.read_text()
    lines = src.splitlines()
    start = next(i for i, line in enumerate(lines) if line.startswith("class ServerConfig"))
    inline = {}
    for tok in tokenize.generate_tokens(io.StringIO(src).readline):
        if tok.type == tokenize.COMMENT and tok.start[0] - 1 > start:
            inline.setdefault(tok.start[0] - 1, tok.string)
    out: dict[str, str] = {}
    field_line = re.compile(r"^    ([a-z_][a-z0-9_]*)\s*:")
    for i in range(start + 1, len(lines)):
        line = lines[i]
        if line and not line.startswith(" "):
            break
        m = field_line.match(line)
        if not m or m.group(1) not in ServerConfig.model_fields:
            continue
        above = []
        j = i - 1
        while j > start and lines[j].strip().startswith("#"):
            above.insert(0, lines[j].strip().lstrip("#").strip())
            j -= 1
        text = " ".join(_drop_heading(above))
        if not lines[i].strip().startswith("#") and i in inline and inline[i] != lines[i].strip():
            text = (text + " " + inline[i].lstrip("#").strip()).strip()
        out[m.group(1)] = text
    # A comment block above a group of fields describes the first one only.
    return out


_HEADING = re.compile(r"^(?:[A-Z][a-z]+)(?: [A-Za-z]+)?$")


def _yaml_comments() -> dict[str, str]:
    """Comments for top-level keys in config/default.yaml: the block just above, and the inline one."""
    if not DEFAULT_YAML.exists():
        return {}
    lines = DEFAULT_YAML.read_text().splitlines()
    out: dict[str, str] = {}
    for i, line in enumerate(lines):
        m = re.match(r"^([a-z_][a-z0-9_]*):(.*)$", line)
        if not m:
            continue
        above, j = [], i - 1
        while j >= 0 and lines[j].startswith("#"):
            above.insert(0, lines[j].lstrip("#").strip())
            j -= 1
        inline = m.group(2).split("#", 1)[1].strip() if "#" in m.group(2) else ""
        out[m.group(1)] = " ".join(_drop_heading(above) + ([inline] if inline else []))
    return out


def _drop_heading(lines: list[str]) -> list[str]:
    """A block that starts with a section label ("Database", "Retention (days)") describes the section."""
    if lines and (_HEADING.match(lines[0]) or re.match(r"^[A-Z][a-z]+ \(.*\)$", lines[0])):
        return lines[1:]
    return lines


