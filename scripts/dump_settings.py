DOCS = ROOT / "docs" / "configuration.md"
COMPOSE = ROOT / "compose.yaml"
COMPOSE_ENV = ROOT / "deploy" / "compose" / ".env.example"
SERVICE_ENV = ROOT / "deploy" / "ltms.env.example"
SETUP_ENV = ROOT / "scripts" / "setup_env.py"  # embeds a copy of the Compose example

BEGIN = "# >>> generated by scripts/dump_settings.py; do not edit between these lines"
END = "# <<< end of generated settings"

# Settings Compose never passes from .env: the database is reached through
# LTMS_DATABASE_URL (built from the LTMS_DB_* values the db service also uses),
# and the image sets LTMS_DEPLOYMENT itself.
