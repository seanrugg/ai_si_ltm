#!/usr/bin/env python3
"""Create a working .env for the LTMS Compose stack, for local or web deploys.

Standard library only: it runs on the host before anything is installed.

Usage:
    python3 scripts/setup_env.py --mode {local,web} [--with-lrs] [--with-mqtt] \
        [--port 8080] [--out .env] [--force]

Starts from deploy/compose/.env.example and writes --out (default .env).
Refuses to overwrite an existing file unless --force is given. The file is
written with mode 0600. Generated passwords and secrets are never printed.
"""

from __future__ import annotations

import argparse
import base64
import os
import secrets
import socket
import subprocess
import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
EXAMPLE = _HERE.parent / "deploy/compose" / ".env.example"

# Embedded copy of deploy/compose/.env.example. Used when the script runs
# standalone, i.e. there is no repo layout next to it. Must stay byte-for-byte
# identical to the repo file; server/tests/test_setup_env.py enforces it.
_EMBEDDED_TEMPLATE = """# LTMS Compose stack environment.
#
# Copy this file to .env at the project root and edit it before starting:
#   cp deploy/compose/.env.example .env
#
# Every secret is a placeholder; replace them with real values. No hostnames,
# domains or site-specific values go here (AGENTS.md rule 10).

# Database: credentials shared by the db and ltms services.
LTMS_DB_NAME=change-me
LTMS_DB_USER=change-me
LTMS_DB_PASSWORD=change-me

# First admin account: created on the first start. Change the password later
# with `docker compose exec ltms python -m server.manage set-admin-password`.
LTMS_ADMIN_USERNAME=change-me
LTMS_ADMIN_PASSWORD=change-me-at-least-16-chars

# Cookie security: true for HTTPS, false only for local HTTP development.
LTMS_COOKIE_SECURE=true

# Port the ltms service publishes on the host.
LTMS_PORT=8080

# Image used by the ltms service. Compose pulls it when it exists and builds
# from the local Dockerfile when asked (`docker compose build`). Pin a tag or
# sha-… (e.g. ghcr.io/seanrugg/ai_si_ltm:v1.2.3 or …@sha256:…) for production.
# LTMS_IMAGE=ghcr.io/seanrugg/ai_si_ltm:latest   # pin a tag or sha-… for production

# Address the ltms port binds to on the host. 127.0.0.1 = this machine only.
LTMS_BIND=127.0.0.1
# Reverse proxy address(es) as seen from the container, trusted for client IPs.
FORWARDED_ALLOW_IPS=127.0.0.1

# --- Optional: --profile mqtt -----------------------------------------------
MQTT_PORT=1883

# --- Optional: --profile lrs (Yet Analytics SQL LRS) --------------------------
# Pin to a release tag, e.g. yetanalytics/lrsql:<version>.
LRSQL_IMAGE=yetanalytics/lrsql:latest
LRS_BIND=127.0.0.1
LRS_PORT=8081
LRSQL_DB_PASSWORD=change-me
LRSQL_ADMIN_USER=change-me
LRSQL_ADMIN_PASS=change-me
# The key/secret LTMS will use when an admin adds this LRS as an endpoint.
LRSQL_API_KEY=change-me
LRSQL_API_SECRET=change-me
# Public address of the LRS admin UI when it is served through a reverse proxy
# (browser logins get 403 without it). Set by setup_env.py --lrs-public-url.
# LRSQL_ALLOWED_ORIGINS=https://lrs.example.org

# --- Values generated by scripts/setup_env.py (do not edit by hand) ---
# LTMS_SECRET_KEY=change-me       # Fernet key: base64 of 32 random bytes
# COMPOSE_PROFILES=change-me      # comma-joined from --with-lrs / --with-mqtt

# --- Optional: --profile lrs -- bootstrap an LRS endpoint on first start (issue #86) ---
# LTMS_LRS_BOOTSTRAP_URL=http://lrs:8080/xapi
# LTMS_LRS_BOOTSTRAP_NAME=sql-lrs
# LTMS_LRS_BOOTSTRAP_USERNAME=change-me   # = LRSQL_API_KEY
# LTMS_LRS_BOOTSTRAP_SECRET=change-me     # = LRSQL_API_SECRET
# LTMS_LRS_BOOTSTRAP_TYPES=perception,thought,decision,action,communication,event,lesson,policy,system
# LTMS_LRS_BOOTSTRAP_XAPI_VERSION=2.0.0
# LTMS_LRS_BOOTSTRAP_ENABLED=true
# LTMS_PUBLIC_BASE_URL=https://ltms.example.org   # base for statement IRIs; required for LRS forwarding

# Remote MCP read access at /mcp (see docs/docker.md). Closed by default.
#   off   - no reads over MCP
#   token - only a valid read token (created on the dashboard's Access page)
#   open  - no token; LTMS_MCP_OPEN_SCOPE applies (payloads are never included)
# LTMS_MCP_READ_MODE=off
# LTMS_MCP_OPEN_SCOPE={"types":["thought","decision","lesson","policy"],"swarms":null}
"""


def _load_template() -> tuple[str, bool]:
    """The .env.example template: the repo file is the source of truth. When
    the script runs standalone and the repo file isn't there, fall back to the
    embedded copy. Returns (template text, True when the repo file was used)."""
    try:
        return EXAMPLE.read_text(encoding="utf-8"), True
    except FileNotFoundError:
        return _EMBEDDED_TEMPLATE, False


def _warn_if_not_git_ignored(out_path: Path) -> None:
    """If out_path lives inside a git work tree and is not git-ignored, warn
    that it holds secrets. Don't fail; skip silently when git is unavailable."""
    try:
        result = subprocess.run(
            ["git", "-C", str(out_path.parent), "check-ignore", "--", out_path.name],
            capture_output=True,
            text=True,
        )
    except (FileNotFoundError, OSError):
        return  # git not available: skip the check silently
    if result.returncode == 1:
        print("this file holds secrets and is not git-ignored", file=sys.stderr)

# All nine LTMS record types (contract v1, section 1.1), comma-separated.
RECORD_TYPES = (
    "perception,thought,decision,action,communication,event,lesson,policy,system"
)

# These keep their fixed values instead of a random one.
FIXED = {
    "LTMS_ADMIN_USERNAME": "admin",
    "LTMS_DB_NAME": "ltms",
    "LTMS_DB_USER": "ltms",
}

# Bootstrap variables (with --with-lrs), in output order.
BOOTSTRAP_VARS = [
    "LTMS_LRS_BOOTSTRAP_URL",
    "LTMS_LRS_BOOTSTRAP_NAME",
    "LTMS_LRS_BOOTSTRAP_USERNAME",
    "LTMS_LRS_BOOTSTRAP_SECRET",
    "LTMS_LRS_BOOTSTRAP_TYPES",
    "LTMS_LRS_BOOTSTRAP_XAPI_VERSION",
    "LTMS_LRS_BOOTSTRAP_ENABLED",
]

# Keys that may be appended when they are not already in the example, in order.
APPEND_ORDER = ["LTMS_SECRET_KEY", "COMPOSE_PROFILES", "LTMS_PUBLIC_BASE_URL", "LRSQL_ALLOWED_ORIGINS"] + BOOTSTRAP_VARS


def _fernet_key() -> str:
    """A Fernet key (base64 of 32 random bytes) without the cryptography package."""
    return base64.urlsafe_b64encode(secrets.token_bytes(32)).decode()


def _random_value(key: str) -> str:
    upper = key.upper()
    if "PASSWORD" in upper or "SECRET" in upper:
        return secrets.token_urlsafe(24)
    if "USER" in upper or "KEY" in upper:
        return secrets.token_hex(8)
    return secrets.token_urlsafe(24)


def _is_placeholder(value: str) -> bool:
    v = value.strip()
    return v == "change-me" or v.startswith("change-me")


def build_values(example_text, mode, with_lrs, with_mqtt, port):
    values = {}
    for line in example_text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or "=" not in stripped:
            continue
        key, _, val = stripped.partition("=")
        key = key.strip()
        if key in FIXED:
            values[key] = FIXED[key]
        elif _is_placeholder(val):
            values[key] = _random_value(key)
        else:
            values[key] = val.strip()

    values["LTMS_BIND"] = "0.0.0.0" if mode == "local" else "127.0.0.1"
    values["LTMS_COOKIE_SECURE"] = "false" if mode == "local" else "true"
    values["FORWARDED_ALLOW_IPS"] = "127.0.0.1" if mode == "local" else "*"
    values["LTMS_PORT"] = str(port)

    if with_lrs:
        values["LTMS_LRS_BOOTSTRAP_URL"] = "http://lrs:8080/xapi"
        values["LTMS_LRS_BOOTSTRAP_NAME"] = "sql-lrs"
        values["LTMS_LRS_BOOTSTRAP_USERNAME"] = values["LRSQL_API_KEY"]
        values["LTMS_LRS_BOOTSTRAP_SECRET"] = values["LRSQL_API_SECRET"]
        values["LTMS_LRS_BOOTSTRAP_TYPES"] = RECORD_TYPES
        values["LTMS_LRS_BOOTSTRAP_XAPI_VERSION"] = "2.0.0"
        values["LTMS_LRS_BOOTSTRAP_ENABLED"] = "true"
    else:
        values["LTMS_LRS_BOOTSTRAP_URL"] = ""

    values["LTMS_SECRET_KEY"] = _fernet_key()
    profiles = [name for name, flag in (("lrs", with_lrs), ("mqtt", with_mqtt)) if flag]
    if profiles:
        values["COMPOSE_PROFILES"] = ",".join(profiles)
    return values


def render(example_text, values, mode):
    out = []
    seen = set()
    for line in example_text.splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            out.append(line)
            continue
        if "=" not in stripped:
            out.append(line)
            continue
        key, _, _ = stripped.partition("=")
        key = key.strip()
        seen.add(key)
        if key in values:
            out.append(f"{key}={values[key]}")
            if key == "FORWARDED_ALLOW_IPS" and mode == "web":
                out.append("# web mode: FORWARDED_ALLOW_IPS=* is safe only because the")
                out.append("# port is bound to 127.0.0.1, so only a proxy on this host")
                out.append("# can reach the ltms port.")
        else:
            out.append(line)

    added_header = False
    for key in APPEND_ORDER:
        if key in values and key not in seen:
            if not added_header:
                out.append("")
                out.append("# --- Values generated by scripts/setup_env.py ---")
                added_header = True
            out.append(f"{key}={values[key]}")
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate a .env for the LTMS Compose stack (local or web mode)."
    )
    parser.add_argument("--mode", required=True, choices=["local", "web"])
    parser.add_argument("--with-lrs", action="store_true")
    parser.add_argument("--with-mqtt", action="store_true")
    parser.add_argument("--port", type=int, default=8080)
    parser.add_argument("--public-url", default=None,
                        help="LTMS_PUBLIC_BASE_URL (base for statement IRIs; required for LRS forwarding). "
                             "Required in web mode (must start with https://). Defaults in local mode.")
    parser.add_argument("--lrs-public-url", default=None,
                        help="Public address of the SQL LRS admin UI behind a reverse proxy "
                             "(LRSQL_ALLOWED_ORIGINS). Needs --with-lrs; https:// in web mode.")
    parser.add_argument("--out", default=".env")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args(argv)

    # LTMS_PUBLIC_BASE_URL: base for statement IRIs; required for LRS forwarding.
    if args.mode == "web":
        if args.public_url is None:
            print("--mode web requires --public-url", file=sys.stderr)
            return 1
        if not args.public_url.startswith("https://"):
            print("--public-url must start with https://", file=sys.stderr)
            return 1
    if args.public_url is None:
        # Local default: http://<hostname lower>[:<port>], with .local appended
        # when the hostname has no dot (so other LAN devices reach it via mDNS).
        host = socket.gethostname().lower()
        if "." not in host:
            host = f"{host}.local"
        args.public_url = f"http://{host}:{args.port}"
    args.public_url = args.public_url.rstrip("/")

    if args.lrs_public_url is not None:
        if not args.with_lrs:
            print("--lrs-public-url needs --with-lrs", file=sys.stderr)
            return 1
        if args.mode == "web" and not args.lrs_public_url.startswith("https://"):
            print("--lrs-public-url must start with https:// in web mode", file=sys.stderr)
            return 1
        args.lrs_public_url = args.lrs_public_url.rstrip("/")

    out_path = Path(args.out)
    if out_path.exists() and not args.force:
        print(f"refusing to overwrite existing file: {out_path}", file=sys.stderr)
        return 1

    _warn_if_not_git_ignored(out_path)

    example_text, from_repo = _load_template()
    print(f"template: {'deploy/compose/.env.example' if from_repo else 'embedded copy'}")
    values = build_values(example_text, args.mode, args.with_lrs, args.with_mqtt, args.port)
    values["LTMS_PUBLIC_BASE_URL"] = args.public_url
    if args.lrs_public_url is not None:
        values["LRSQL_ALLOWED_ORIGINS"] = args.lrs_public_url
    text = render(example_text, values, args.mode)

    # Create the file with mode 0600 from the start: writing first and chmod-ing
    # after would leave the secrets world-readable for a moment (umask 022).
    # Without --force, O_EXCL also closes the race with the exists() check above.
    flags = os.O_WRONLY | os.O_CREAT | (os.O_TRUNC if args.force else os.O_EXCL)
    fd = os.open(out_path, flags, 0o600)
    # newline="\n": LF on every platform, even when the platform default is CRLF.
    with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    os.chmod(out_path, 0o600)  # an existing file overwritten with --force keeps its old mode otherwise

    profiles = values.get("COMPOSE_PROFILES", "")
    print(f"wrote {out_path}")
    print(f"mode: {args.mode}")
    print(f"profiles: {profiles or '(none)'}")
    print(f"admin username: {values['LTMS_ADMIN_USERNAME']}")
    print("admin password: in .env (LTMS_ADMIN_PASSWORD)")
    print(f"public base URL: {values['LTMS_PUBLIC_BASE_URL']}")
    if args.lrs_public_url is not None:
        print(f"LRS admin UI: {args.lrs_public_url}/admin (user LRSQL_ADMIN_USER, password LRSQL_ADMIN_PASS in .env)")
    print("next: docker compose up -d")
    if args.mode == "local":
        print("warning: the dashboard login travels over plain HTTP on your network")
    return 0


if __name__ == "__main__":
    sys.exit(main())
